// Calibrate the in situ kinetics (js/insitu-cal.js) against measured data.
//
//   node tools/calibrate/calibrate.mjs --published
//       refit the published datasets and rewrite js/calibration-published.js (the default profile) and
//       tools/calibrate/published-report.json
//
//   node tools/calibrate/calibrate.mjs --session my-session.json --series my-series.csv [--targets my-targets.json]
//       [--fit sinter_A,sinter_Ea] [--name "3200FS, Au on SiNx, 2026-11"] [--base published|none] [--out my-calibration.json]
//       fit your own measurements: the session (Data → Save session in the exhibit) gives the conditions and the
//       timeline; the CSV has t_s and observable columns (Data → Calibration → Template CSV writes one); targets are
//       scalar results ([{ "model": "nuc_dose", "at": { "lcRate": 2 }, "value": 30, "sigma": 5 }, ...]).
//       Load the profile in the exhibit (Calibration → Load profile) or pass it to the headless runner.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import * as C from '../../js/insitu-cal.js';
import { readSession } from '../../js/session.js';

const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..', '..');
const args = process.argv.slice(2), opt = (k) => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : undefined; };
const show = (profile) => {
  for (const [k, e] of Object.entries(profile.params)) console.log(`  ${k.padEnd(10)} ${String(e.v).padStart(10)}  ±${(100 * e.unc).toFixed(0)} %  (${e.dataset})`);
  for (const r of profile.fit.report) {
    console.log(`  ${r.id}: ${r.title}`);
    for (const t of r.targets) console.log(`    target ${t.what ?? t.id}: measured ${t.value} ± ${t.sigma} ${t.unit ?? ''}, model ${t.predicted}`);
    for (const t of r.checks) console.log(`    check  ${t.what ?? t.id}: ${t.value != null ? `measured ${t.value} ± ${t.sigma}, ` : ''}model ${t.predicted} ${t.unit ?? ''}`);
    if (r.series) console.log(`    series ${r.series.points} points: ${r.series.columns.join(', ')}`);
  }
  console.log(`  χ² ${profile.fit.chi2} over ${profile.fit.points} points (reduced ${profile.fit.reduced_chi2})`);
};

if (args.includes('--published')) {
  const created = new Date().toISOString().slice(0, 10);
  const { profile } = C.fit(C.PUBLISHED_SETS, { base: null, name: 'Published in situ series', created });
  const { report, ...fitSummary } = profile.fit;
  const lean = { ...profile, fit: fitSummary };
  writeFileSync(join(root, 'js', 'calibration-published.js'), `// generated by tools/calibrate/calibrate.mjs --published; do not edit by hand (the report: tools/calibrate/published-report.json)\nexport const PUBLISHED = ${JSON.stringify(lean, null, 2)};\n`);
  writeFileSync(join(here, 'published-report.json'), JSON.stringify(profile, null, 2) + '\n');
  console.log('published calibration:'); show(profile);
} else {
  const sessF = opt('session'), serF = opt('series'), tgF = opt('targets');
  if (!sessF || (!serF && !tgF)) { console.error('usage: --published, or --session <file> with --series <csv> and/or --targets <json> (see the header of this file)'); process.exit(2); }
  const { state, warnings } = readSession(JSON.parse(readFileSync(sessF, 'utf8')));
  warnings.forEach((w) => console.warn(`session: ${w}`));
  const ser = serF ? C.parseSeriesCSV(readFileSync(serF, 'utf8')) : { rows: [], columns: [], ignored: [] };
  if (ser.ignored.length) console.warn(`columns ignored (not observables): ${ser.ignored.join(', ')}`);
  const targets = tgF ? JSON.parse(readFileSync(tgF, 'utf8')) : [];
  const fitKeys = opt('fit')?.split(',').map((s) => s.trim()).filter(Boolean);
  const d = C.userDataset(state, { rows: ser.rows, targets, fitKeys, id: opt('id') ?? 'mine', title: opt('name') ?? 'My measurements', ref: opt('ref') ?? '' });
  if (!d.fit.length) { console.error('nothing to fit: name the parameters with --fit (e.g. sinter_A,sinter_Ea)'); process.exit(2); }
  const { profile } = C.fit([d], { base: opt('base') === 'none' ? null : C.PUBLISHED, name: opt('name') ?? 'My calibration' });
  const out = opt('out') ?? 'my-calibration.json';
  writeFileSync(out, JSON.stringify(profile, null, 2) + '\n');
  console.log(`fitted ${d.fit.join(', ')}; wrote ${out}`); show(profile);
}
